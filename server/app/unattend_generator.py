_JINJA_OPEN = re.compile(r"\{(?=[{%#])")
_DECLARATION = re.compile(r"\A(<\?xml[^>]*\?>)(\r?\n)")
_MAX_OUTPUT = 16 * 1024 * 1024


class GeneratorUnavailable(Exception):
    """The generator program is missing or did not run."""


class GeneratorError(Exception):
    """The settings cannot be turned into an answer file. The messages are meant for users."""

    def __init__(self, errors: list[str]):
        super().__init__("; ".join(errors))
        self.errors = errors


def jinja_escape(text: str) -> str:
    """Make ``text`` render to itself in Jinja: escape each ``{`` that opens a tag."""
    return _JINJA_OPEN.sub('{{ "{" }}', text)


def to_template(xml: str, upstream_commit: str | None) -> str:
    """Turn the program's XML into a netdispatch template (see the module docstring)."""
    text = jinja_escape(xml)
    for token, variable in TOKENS.items():
        text = text.replace(token, variable)
    comment = (
        "<!-- Generated by the netdispatch unattend generator"
        + (f" (unattend-generator {upstream_commit})" if upstream_commit else "")
        + ". This file is rewritten whenever the template is saved in the generator; to edit "
        "the XML by hand, convert the template to raw XML first. -->"
    )
    match = _DECLARATION.match(text)
    if match:
        newline = match.group(2)
        return match.group(1) + newline + comment + newline + text[match.end() :]
    return comment + "\r\n" + text


def migrate_settings(settings: dict[str, Any]) -> dict[str, Any]:
    """Bring stored settings to SCHEMA_VERSION. Version 1 is the first, so nothing to do yet."""
    return settings


class UnattendGenerator:
    def __init__(self, binary: Path, timeout: float = 30.0, max_parallel: int = 2):
        self.binary = binary
        self.timeout = timeout
        self._slots = threading.BoundedSemaphore(max_parallel)
        self._schema_lock = threading.Lock()
        self._schema: tuple[tuple[int, int], dict[str, Any]] | None = None

    @property
    def available(self) -> bool:
        return self.binary.is_file() and os.access(self.binary, os.X_OK)

    def _run(self, command: str, stdin: bytes = b"") -> tuple[int, bytes]:
        if not self.available:
            raise GeneratorUnavailable(f"the unattend generator is not installed at {self.binary}")
        env = {
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
            "HOME": os.environ.get("HOME", "/tmp"),
            "TMPDIR": os.environ.get("TMPDIR", "/tmp"),
            "DOTNET_CLI_TELEMETRY_OPTOUT": "1",
            "DOTNET_NOLOGO": "1",
            # One process per call: a small heap and no diagnostics IPC socket.
            "DOTNET_gcServer": "0",
            "DOTNET_EnableDiagnostics": "0",
        }
        with self._slots:
            try:
                proc = subprocess.run(
                    [str(self.binary), command],
                    input=stdin,
                    capture_output=True,
                    timeout=self.timeout,
                    env=env,
                    check=False,
                )
            except subprocess.TimeoutExpired as exc:
                raise GeneratorUnavailable(f"the unattend generator did not finish within {self.timeout:g} s") from exc
            except OSError as exc:
                raise GeneratorUnavailable(f"the unattend generator could not be started: {exc}") from exc
        if len(proc.stdout) > _MAX_OUTPUT:
            raise GeneratorUnavailable("the unattend generator produced too much output")
        if proc.returncode not in (0, 2):
            log.error(
                "netdispatch-unattendgen %s exited with %s: %s",
                command,
                proc.returncode,
                proc.stderr.decode("utf-8", "replace")[-4000:],
            )
            raise GeneratorUnavailable(f"the unattend generator failed (exit code {proc.returncode}); see the server log")
        return proc.returncode, proc.stdout

    def schema(self) -> dict[str, Any]:
        """Defaults, switches and lists of choices, cached until the program changes."""
        try:
            stat = self.binary.stat()
        except OSError as exc:
            raise GeneratorUnavailable(f"the unattend generator is not installed at {self.binary}") from exc
        key = (stat.st_mtime_ns, stat.st_size)
        with self._schema_lock:
            if self._schema is None or self._schema[0] != key:
                _, out = self._run("schema")
                self._schema = (key, json.loads(out))
            return self._schema[1]

    @property
    def upstream_commit(self) -> str | None:
        return self.schema().get("upstreamCommit")

    def generate(self, settings: dict[str, Any]) -> tuple[str, list[str]]:
        """Run the library. Returns the raw XML and any warnings."""
        payload = json.dumps(migrate_settings(settings)).encode("utf-8")
        code, out = self._run("generate", payload)
        result = json.loads(out)
        if code == 2:
            raise GeneratorError([str(e) for e in result.get("errors") or ["invalid settings"]])
        return result["xml"], [str(w) for w in result.get("warnings") or []]

    def build_template(self, settings: dict[str, Any]) -> tuple[str, list[str]]:
        """Generate and convert to a template that passes ``unattend.validate``."""
        xml, warnings = self.generate(settings)
        template = to_template(xml, self.upstream_commit)
        if err := validate(template):
            # The escaping above should make this impossible; treat it as a bug, not bad input.
            log.error("generated template does not validate: %s", err)
            raise GeneratorUnavailable(f"the generated answer file did not validate: {err}")
        return template, warnings
