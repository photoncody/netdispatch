"""Built-in answer-file generator.

The XML comes from ``netdispatch-unattendgen`` (built from ``server/unattendgen``), a small
command-line wrapper around the unattend-generator library behind schneegans.de. This module
runs it, then turns its output into an ordinary netdispatch template:

1. Every ``{`` that would start a Jinja tag (``{{``, ``{%``, ``{#``) is escaped, because saved
   templates are rendered with Jinja when a device downloads them and generated PowerShell is
   full of braces.
2. Placeholders the settings may contain (``__ND_HOSTNAME__`` from the "netdispatch hostname"
   computer-name mode, or typed into a script) become template variables. They are replaced
   after escaping, so the variables are the only Jinja in the result.
3. A comment saying where the file came from is added after the XML declaration.

The program only runs when a template is previewed or saved, never while a device boots: the
saved file is what ``/files/d/{token}/autounattend.xml`` serves.
"""

from __future__ import annotations

import json
import logging
import os
import re
import subprocess
import threading
from pathlib import Path
from typing import Any

from .unattend import validate

log = logging.getLogger("netdispatch.unattend_generator")

# Bump together with migrate_settings() when netdispatch changes the stored settings format.
# The CLI checks the same number (HostConfig.CurrentSchemaVersion).
SCHEMA_VERSION = 1

# Placeholder -> template variable. Each placeholder is at least as long as any value its
# variable can take, so text the library packs into length-limited commands still fits.
TOKENS = {
    "__ND_HOSTNAME__": "{{ hostname }}",
    "__ND_MAC_PLAIN__": "{{ mac_plain }}",
}

# Settings for a new generated template: a hands-off Windows 11 Pro install that wipes disk 0
# and names the computer after the device. The form's other values default to the library's.
