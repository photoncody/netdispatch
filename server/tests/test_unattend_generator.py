    rendered = render(tpl, sample_context())
    ET.fromstring(rendered.encode())
    for marker in ("nd-system", "nd-default", "nd-firstlogon {% x %}", "nd-useronce {# c #}", '"a"="{{b}}"'):
        assert marker in rendered.replace("&quot;", '"'), marker


