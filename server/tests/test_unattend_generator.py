"""The built-in unattend generator (netdispatch-unattendgen + app.unattend_generator)."""

from __future__ import annotations

import copy
import re
import xml.etree.ElementTree as ET

import pytest

from app.unattend import render, sample_context, validate
from app.unattend_generator import (
    NEW_TEMPLATE_SETTINGS,
    GeneratorError,
    GeneratorUnavailable,
    UnattendGenerator,
    jinja_escape,
    to_template,
)

NS = {"u": "urn:schemas-microsoft-com:unattend"}
MAC = "52-54-00-AB-CD-01"
Q = f"/boot?mac={MAC}&ip=10.0.0.42&relay=site-a&arch=x86_64&platform=efi"


def new_settings(**changes):
    s = copy.deepcopy(NEW_TEMPLATE_SETTINGS)
    s.update(changes)
    return s


# ----------------------------------------------------------- escaping (no program needed)
@pytest.mark.parametrize(
    "text",
    [
        "plain",
        "{{ x }}",
        "{% if %}",
        "{# c #}",
        "{{{",
        "{{%#",
        "}} %} #}",
        "$h = @{ a = 1 }; if ($x) {{ $y }}",
        "{\n{{\n",
        "{\r\n{{\r\n",
        "'{{'\"{%\"",
    ],
)
def test_jinja_escape_renders_to_itself(text):
    assert render(jinja_escape(text), {}) == text


def test_to_template_inserts_variables_and_header():
    xml = '<?xml version="1.0" encoding="utf-8"?>\r\n<unattend><c>__ND_HOSTNAME__</c><s>{{ $x }} __ND_MAC_PLAIN__</s></unattend>\r\n'
    tpl = to_template(xml, "a" * 40)
    lines = tpl.split("\r\n")
    assert lines[0] == '<?xml version="1.0" encoding="utf-8"?>'
    assert lines[1].startswith("<!-- Generated by the netdispatch unattend generator (unattend-generator aaaa")
    assert validate(tpl) is None
    rendered = render(tpl, sample_context())
    assert "<c>ND-123456</c><s>{{ $x }} 525400123456</s>" in rendered
    assert "\n" not in rendered.replace("\r\n", "")


def test_missing_program_is_reported(tmp_path):
    gen = UnattendGenerator(tmp_path / "nope")
    assert not gen.available
    with pytest.raises(GeneratorUnavailable):
        gen.schema()
    with pytest.raises(GeneratorUnavailable):
        gen.generate({})


def test_api_without_program_returns_503(admin, app, tmp_path):
    app.state.unattend_generator = UnattendGenerator(tmp_path / "nope")
    assert admin.get("/api/unattend/generator/schema").status_code == 503
    r = admin.post("/api/unattend/generator", json={"name": "x", "settings": {}})
    assert r.status_code == 503
    # Raw templates keep working.
    assert admin.post("/api/unattend", json={"name": "raw", "content": "<a/>"}).status_code == 201
    assert admin.get("/api/unattend").status_code == 200


# ----------------------------------------------------------- the real program
@pytest.fixture
def gen(unattendgen):
    return UnattendGenerator(unattendgen)


def test_schema(gen):
    schema = gen.schema()
    assert re.fullmatch(r"[0-9a-f]{40}", schema["upstreamCommit"])
    assert schema["hostnameToken"] == "__ND_HOSTNAME__"
    assert schema["defaults"]["computerName"]["mode"] == "Random"
    assert any(f["name"] == "DisableUac" for f in schema["flags"])
    for key in ("imageLanguages", "userLocales", "keyboards", "geoLocations", "timeZones", "windowsEditions", "bloatware"):
        assert schema[key], key
    assert gen.schema() is schema  # cached


def test_new_template_settings_generate_a_hands_off_install(gen):
    xml, warnings = gen.generate(NEW_TEMPLATE_SETTINGS)
    root = ET.fromstring(xml.encode())
    assert root.tag == "{urn:schemas-microsoft-com:unattend}unattend"
    names = root.findall(".//u:settings[@pass='specialize']/u:component/u:ComputerName", NS)
    assert [n.text for n in names] == ["__ND_HOSTNAME__"]
    # The generated pe.cmd partitions the disk and finds the answer file through the
    # registry value netdispatch.cmd sets.
    assert "X:\\pe.cmd" in xml
    assert "UnattendFile" in xml
    assert isinstance(warnings, list)


def test_build_template_renders_hostname_once(gen):
    tpl, _ = gen.build_template(NEW_TEMPLATE_SETTINGS)
    assert tpl.count("<ComputerName>{{ hostname }}</ComputerName>") == 1
    rendered = render(tpl, sample_context())
    assert "<ComputerName>ND-123456</ComputerName>" in rendered
    ET.fromstring(rendered.encode())
    assert "\n" not in rendered.replace("\r\n", "")  # CRLF throughout


def test_scripts_with_braces_survive(gen):
    ps = "$h = @{ a = 1 }; if ($true) {{ Write-Output '{{x}}' }} # {% %} {# #}"
    s = new_settings(
        computerName={"mode": "Random"},
        scripts={"items": [{"phase": "FirstLogon", "type": "Ps1", "content": ps}]},
    )
    raw, _ = gen.generate(s)
    tpl, _ = gen.build_template(s)
    rendered = render(tpl, sample_context())
    # Everything but the added header comment matches the program's own output.
    assert rendered.replace(tpl.split("\r\n")[1] + "\r\n", "", 1) == raw


def test_invalid_settings_raise(gen):
    with pytest.raises(GeneratorError) as exc:
        gen.generate(new_settings(computerName={"mode": "Custom", "name": "has space"}))
    assert any("Computer name" in e for e in exc.value.errors)
    with pytest.raises(GeneratorError):
        gen.generate({"bogus": True})


# ----------------------------------------------------------- API
def test_generator_lifecycle(admin, settings, unattendgen, windows_iso, client):
    schema = admin.get("/api/unattend/generator/schema")
    assert schema.status_code == 200
    assert schema.json()["newTemplate"] == NEW_TEMPLATE_SETTINGS

    preview = admin.post("/api/unattend/generator/preview", json={"settings": NEW_TEMPLATE_SETTINGS})
    assert preview.status_code == 200, preview.text
    assert "<ComputerName>ND-123456</ComputerName>" in preview.json()["rendered"]

    bad = admin.post("/api/unattend/generator/preview", json={"settings": {"bogus": 1}})
    assert bad.status_code == 422

    r = admin.post("/api/unattend/generator", json={"name": "Win11 lab", "settings": NEW_TEMPLATE_SETTINGS})
    assert r.status_code == 201, r.text
    tpl = r.json()
    assert tpl["generated"] is True and tpl["stale"] is False
    assert tpl["settings"] == NEW_TEMPLATE_SETTINGS
    on_disk = (settings.configs_dir / tpl["filename"]).read_bytes()
    assert b"\r\n" in on_disk

    listed = next(t for t in admin.get("/api/unattend").json() if t["id"] == tpl["id"])
    assert listed["generated"] is True
    detail = admin.get(f"/api/unattend/{tpl['id']}").json()
    assert detail["settings"] == NEW_TEMPLATE_SETTINGS and detail["content"] == on_disk.decode()

    # Raw edits are refused while it is generated.
    assert admin.put(f"/api/unattend/{tpl['id']}", json={"name": "x", "content": "<a/>"}).status_code == 409

    # Regenerate with changed settings.
    changed = new_settings(timeZone={"mode": "Explicit", "id": "W. Europe Standard Time"})
    r = admin.put(f"/api/unattend/generator/{tpl['id']}", json={"name": "Win11 lab", "settings": changed})
    assert r.status_code == 200, r.text
    assert "<TimeZone>W. Europe Standard Time</TimeZone>" in (settings.configs_dir / tpl["filename"]).read_text()
    invalid = admin.put(f"/api/unattend/generator/{tpl['id']}", json={"name": "Win11 lab", "settings": {"bogus": 1}})
    assert invalid.status_code == 422
    assert "W. Europe" in (settings.configs_dir / tpl["filename"]).read_text()  # unchanged

    # Deploy: the device gets the rendered file with its own hostname and CRLF intact.
    client.get(Q)
    dev = next(d for d in admin.get("/api/devices").json() if d["mac"] == "52:54:00:ab:cd:01")
    admin.post(
        f"/api/devices/{dev['id']}/deploy",
        json={"iso_id": windows_iso, "unattend_id": tpl["id"], "label": "Lab PC 7"},
    )
    script = client.get(Q).text
    token = re.search(r"/files/d/([A-Za-z0-9_-]+)/autounattend.xml", script).group(1)
    served = client.get(f"/files/d/{token}/autounattend.xml").text
    assert "<ComputerName>Lab-PC-7</ComputerName>" in served
    assert "\n" not in served.replace("\r\n", "")
    ET.fromstring(served.encode())

    # Convert to raw XML: settings go, file stays, raw edits work.
    r = admin.post(f"/api/unattend/{tpl['id']}/detach")
    assert r.status_code == 200 and r.json()["generated"] is False
    assert admin.post(f"/api/unattend/{tpl['id']}/detach").status_code == 409
    assert admin.put(f"/api/unattend/generator/{tpl['id']}", json={"name": "x", "settings": changed}).status_code == 409
    assert admin.put(f"/api/unattend/{tpl['id']}", json={"name": "raw now", "content": "<a/>"}).status_code == 200


def test_delete_generated_removes_settings(admin, app, unattendgen):
    from app.models import UnattendGenerated

    tpl = admin.post("/api/unattend/generator", json={"name": "gone", "settings": NEW_TEMPLATE_SETTINGS}).json()
    assert admin.delete(f"/api/unattend/{tpl['id']}").status_code == 204
    with app.state.sessionmaker() as db:
        assert db.get(UnattendGenerated, tpl["id"]) is None


def test_generated_name_clash(admin, unattendgen):
    admin.post("/api/unattend", json={"name": "taken", "content": "<a/>"})
    r = admin.post("/api/unattend/generator", json={"name": "taken", "settings": NEW_TEMPLATE_SETTINGS})
    assert r.status_code == 409


def test_older_engine_is_flagged(admin, app, unattendgen):
    from app.models import UnattendGenerated

    tpl = admin.post("/api/unattend/generator", json={"name": "old", "settings": NEW_TEMPLATE_SETTINGS}).json()
    with app.state.sessionmaker() as db:
        db.get(UnattendGenerated, tpl["id"]).upstream_commit = "0" * 40
        db.commit()
    assert admin.get(f"/api/unattend/{tpl['id']}").json()["stale"] is True
